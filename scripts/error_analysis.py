"""Error analysis and calibration of the shipped model (character n-gram SVM) on the held-out test split.

    python benchmark.py --export-primary
    python scripts/error_analysis.py          # writes reports/error_analysis.md, calibration.json, calibration.png

Descriptive only: the test split is not used to change the model or threshold after this.
"""
import json
import re
import sys
from pathlib import Path

import joblib
import matplotlib
import numpy as np

matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from benchmark import splits  # noqa: E402

BINS = 10
CATEGORIES = [  # first match wins; rules are transparent keyword heuristics, not a learned taxonomy
    ('contains a URL', lambda t: bool(re.search(r'https?://|www\.|\w+\.(com|co\.uk|net|org)\b', t, re.I))),
    ('contains a long phone/short-code number', lambda t: bool(re.search(r'\d{5,}', t))),
    ('promotional words (free, win, prize, offer, claim, cash, txt, reply)', lambda t: bool(re.search(r'\b(free|win|won|prize|offer|claim|cash|txt|reply|text|stop)\b', t, re.I))),
    ('very short (<= 6 words)', lambda t: len(t.split()) <= 6),
]


def category(text):
    return next((name for name, test in CATEGORIES if test(text)), 'other')


def calibration(y, p):
    edges = np.linspace(0, 1, BINS + 1)
    idx = np.clip(np.digitize(p, edges[1:-1]), 0, BINS - 1)
    rows, ece = [], 0.0
    for b in range(BINS):
        mask = idx == b
        if mask.any():
            conf, acc = float(p[mask].mean()), float(y[mask].mean())
            ece += mask.mean() * abs(conf - acc)
            rows.append({'bin': f'{edges[b]:.1f}-{edges[b + 1]:.1f}', 'n': int(mask.sum()), 'mean_predicted': round(conf, 4), 'observed_spam_rate': round(acc, 4)})
    return rows, round(float(ece), 4), round(float(((p - y) ** 2).mean()), 4)


def main():
    path = ROOT / 'models' / 'spamshield_svm.joblib'
    if not path.exists():
        sys.exit('Run python benchmark.py --export-primary first')
    data, _ = splits()
    texts, y = data['test']
    model = joblib.load(path)
    p = model.predict_proba(texts)[:, 1]
    pred = (p >= .5).astype(int)
    rows, ece, brier = calibration(y, p)
    (ROOT / 'reports' / 'calibration.json').write_text(json.dumps({'bins': rows, 'ece_10_bins': ece, 'brier': brier, 'n': len(y)}, indent=2), encoding='utf-8')

    fig, ax = plt.subplots(1, 2, figsize=(9, 4))
    ax[0].plot([0, 1], [0, 1], '--', color='gray', label='perfect')
    ax[0].plot([r['mean_predicted'] for r in rows], [r['observed_spam_rate'] for r in rows], 'o-', color='#1f6feb', label='char SVM')
    ax[0].set(xlabel='mean predicted spam probability', ylabel='observed spam rate', title=f'Reliability (ECE {ece}, Brier {brier})')
    ax[0].legend()
    ax[1].hist([p[y == 0], p[y == 1]], bins=20, label=['ham', 'spam'], color=['#2da44e', '#cf222e'], log=True)
    ax[1].set(xlabel='predicted spam probability', ylabel='messages (log)', title='Score distribution, test split')
    ax[1].legend()
    fig.tight_layout()
    fig.savefig(ROOT / 'reports' / 'calibration.png', dpi=110)

    errors = [(t, int(a), float(s)) for t, a, s, q in zip(texts, y, p, pred) if a != q]
    lines = ['# Error analysis: character n-gram SVM on the 1,032-message test split', '',
             f'Generated by `python scripts/error_analysis.py`. Threshold 0.5. {sum(1 for e in errors if e[1] == 0)} false positives, {sum(1 for e in errors if e[1] == 1)} false negatives.',
             f'Calibration: ECE {ece} (10 equal-width bins), Brier {brier}; see `calibration.png` and `calibration.json`.', '',
             'Categories are keyword heuristics (first match wins), so counts are rough. The test split was inspected here for description only; nothing was tuned on it.', '']
    for title, actual in (('False positives (ham flagged as spam)', 0), ('False negatives (spam that got through)', 1)):
        subset = sorted((e for e in errors if e[1] == actual), key=lambda e: -abs(e[2] - actual))
        counts = {}
        for e in subset:
            counts[category(e[0])] = counts.get(category(e[0]), 0) + 1
        lines += [f'## {title}: {len(subset)}', '', '| Category | Count |', '| --- | --- |'] + [f'| {k} | {v} |' for k, v in sorted(counts.items(), key=lambda kv: -kv[1])]
        lines += ['', '| P(spam) | Category | Message |', '| --- | --- | --- |']
        lines += [f'| {s:.2f} | {category(t)} | {t.replace("|", "/").replace(chr(10), " ")[:200]} |' for t, _, s in subset]
        lines.append('')
    (ROOT / 'reports' / 'error_analysis.md').write_text('\n'.join(lines), encoding='utf-8')
    print(json.dumps({'ece': ece, 'brier': brier, 'errors': len(errors)}))


if __name__ == '__main__':
    main()
